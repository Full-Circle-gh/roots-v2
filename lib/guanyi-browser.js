// Playwright browser automation for the Guanyi C-ERP merchant backend
// (gzgrocery's 管易云 tenant, v2.guanyierp.com). Mirrors lib/meituan-browser:
// a persisted logged-in session drives the channel via its OWN JSON APIs
// (captured from the live UI), issued as cookie-authenticated fetches from the
// logged-in page — no UI clicking, no request signing.
//
// Two differences from Meituan:
//   1. Login is username+password (no QR). The session is created once by the
//      standalone scripts/guanyi-login.js (a human types the password — we never
//      automate credential entry) and restored headless thereafter.
//   2. Stock is an ERP ledger, so it cannot be SET to an absolute number. Each
//      change is a document: 其他入库单 (inbound, adds qty) or 其他出库单
//      (outbound, removes qty), created then 审核 (approved). The daemon computes
//      target − current and calls applyDeltas() to build the right document.

/* global document --
   a browser global referenced INSIDE a page.evaluate() callback, which runs in the
   logged-in Chrome page context (not Node). Declaring it keeps the deploy's eslint
   no-undef gate happy without disabling the rule for genuine Node typos. Same
   treatment as lib/qingyun-browser.js and lib/meituan-browser.js. */

const path = require('path');
const fs   = require('fs');
const { browserEnv } = require('./browser-env');
// Reuse Meituan's coherent Windows fingerprint (pure function) — same region,
// same anti-bot needs; no behavioural coupling between the two channels.
const { fingerprintInitScript } = require('./meituan-browser');

const SESSION_DIR = path.join(__dirname, '../data/guanyi-sessions');
const BASE_URL    = 'https://v2.guanyierp.com';
const HOME_URL    = `${BASE_URL}/index`;

// The exact filter payload the inventory-query grid posts. No token/auth field —
// the session cookie is the only credential. rows=1000 returns the full Roots
// product set (244 today) in one page.
const LIST_FORM = {
  page: '1', rows: '1000', start: '0', disable: 'false', skuDel: '', mergeWarehouse: '',
  exactOrFuzzyByCode: '0', exactOrFuzzyBySkuCode: '0', skuNameScopeType: '0',
  exactOrFuzzyByBarCode: '0', nameScopeType: '0', qtyType: '1',
};

let playwright;
function getPlaywright() {
  if (!playwright) playwright = require('playwright');
  return playwright;
}

// RFC4122-ish v4 uuid (crypto-backed). Guanyi forms carry a per-submit `token`
// and a `no_repeat_*` anti-resubmit token, both plain uuids generated by the
// client — we mint fresh ones per document.
function uuid() {
  const b = require('crypto').randomBytes(16);
  b[6] = (b[6] & 0x0f) | 0x40;
  b[8] = (b[8] & 0x3f) | 0x80;
  const h = b.toString('hex');
  return `${h.slice(0,8)}-${h.slice(8,12)}-${h.slice(12,16)}-${h.slice(16,20)}-${h.slice(20)}`;
}

// Optional outbound proxy, same mechanism as Meituan: per-store GUANYI_PROXY_<CODE>
// wins, else shared GUANYI_PROXY_URL. Unset → direct.
function resolveProxy(storeCode) {
  const raw = (storeCode && process.env[`GUANYI_PROXY_${String(storeCode).toUpperCase()}`])
    || process.env.GUANYI_PROXY_URL || '';
  if (!raw) return null;
  try {
    const u = new URL(raw);
    const proxy = { server: `${u.protocol}//${u.host}` };
    if (u.username) proxy.username = decodeURIComponent(u.username);
    if (u.password) proxy.password = decodeURIComponent(u.password);
    return proxy;
  } catch (e) {
    console.error(`[guanyi] ignoring malformed proxy URL: ${e.message}`);
    return null;
  }
}

class GuanyiBrowser {
  constructor(storeCode) {
    this.storeCode   = storeCode;
    this.sessionFile = path.join(SESSION_DIR, `${storeCode}-session.json`);
    this.browser     = null;
    this.context     = null;
    this.page        = null;
    this._loggedIn   = false;
    this.warehouseId = process.env.GUANYI_WAREHOUSE_ID || null; // discovered from listings if unset
  }

  // ── Lifecycle ──────────────────────────────────────────────────────────────

  async init(opts = {}) {
    if (!fs.existsSync(SESSION_DIR)) fs.mkdirSync(SESSION_DIR, { recursive: true });
    const { chromium } = getPlaywright();

    const useSession = !opts.ignoreSession && fs.existsSync(this.sessionFile);
    const storageState = useSession ? JSON.parse(fs.readFileSync(this.sessionFile, 'utf8')) : undefined;
    const headless = opts.headed ? false : useSession;
    this._log(useSession ? 'restoring session (headless)'
      : (opts.ignoreSession ? 'fresh login (existing session kept until new login succeeds)'
                            : 'no session — launching headed for manual login'));

    const isWindows = process.platform === 'win32';
    const stealthArgs = ['--disable-blink-features=AutomationControlled'];
    const launchOpts = {
      headless,
      // Same D-Bus abort guard as the Meituan browser — see lib/browser-env.
      env: browserEnv(),
      args: isWindows
        ? [...stealthArgs, '--disable-gpu', '--disable-dev-shm-usage']
        : ['--no-sandbox', '--disable-setuid-sandbox', '--disable-dev-shm-usage', '--disable-background-networking', '--disable-sync', '--disable-component-update', '--disable-default-apps', '--disable-breakpad', '--disable-domain-reliability', '--no-pings', '--disk-cache-size=33554432', '--media-cache-size=16777216', '--disable-gpu-shader-disk-cache', ...stealthArgs],
    };
    if (isWindows) {
      const edgePath = 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe';
      if (fs.existsSync(edgePath)) launchOpts.executablePath = edgePath;
      else launchOpts.channel = 'msedge';
    }
    const proxy = resolveProxy(this.storeCode);
    if (proxy) { launchOpts.proxy = proxy; this._log(`using proxy ${proxy.server}`); }

    this.browser = await chromium.launch(launchOpts);

    let chromeVer = '124.0.0.0';
    try { const m = String(this.browser.version()).match(/(\d+\.\d+\.\d+\.\d+)/); if (m) chromeVer = m[1]; } catch (e) {}
    const chromeMajor = chromeVer.split('.')[0];
    const userAgent = `Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/${chromeVer} Safari/537.36`;

    this.context = await this.browser.newContext({
      storageState, userAgent,
      viewport: { width: 1920, height: 1080 },
      locale: 'zh-CN', timezoneId: 'Asia/Shanghai',
    });
    await this.context.addInitScript(fingerprintInitScript, { chromeVer, chromeMajor });
    this.page = await this.context.newPage();
  }

  // The dashboard is reached when /index renders (it shows 登录用户 / the menu)
  // and we were NOT bounced to a login page.
  async _isLoggedInPage() {
    try {
      const url = this.page.url();
      if (/\/login|passport|sso/i.test(url)) return false;
      return await this.page.evaluate(() => {
        const t = document.body ? document.body.innerText : '';
        return t.includes('登录用户') || t.includes('商品库存查询') || t.includes('数据看板');
      });
    } catch (e) { return false; }
  }

  async ensureLoggedIn() {
    if (this._loggedIn) return true;
    await this.page.goto(HOME_URL, { waitUntil: 'domcontentloaded', timeout: 30000 });
    await this._humanPause(2500, 4200);
    if (await this._isLoggedInPage()) {
      this._loggedIn = true;
      await this._saveSession();
      this._log('login confirmed');
      return true;
    }
    this._log('session expired or missing — run scripts/guanyi-login.js to create one');
    return false;
  }

  // Headed interactive login for the standalone helper. Keeps the window open so
  // a human can type the account + password (and any SMS code). Succeeds only
  // when the real dashboard is shown. Not called by the daemon.
  async interactiveLogin(maxMs = 360000) {
    await this.page.goto(HOME_URL, { waitUntil: 'domcontentloaded', timeout: 30000 });
    await this.page.waitForTimeout(5000);
    this._log('window open — log in with the Guanyi account + password; waiting for dashboard…');
    const deadline = Date.now() + maxMs;
    while (Date.now() < deadline) {
      try {
        await this.page.waitForTimeout(2500);
        if (await this._isLoggedInPage()) {
          this._loggedIn = true;
          await this._saveSession();
          this._log('login successful — session saved');
          return true;
        }
      } catch (e) {
        const msg = String(e.message || '');
        if (/crash|has been closed|Target (page|closed)/i.test(msg)) {
          this._log(`recovering from page crash: ${msg.slice(0, 50)}`);
          try {
            this.page = await this.context.newPage();
            await this.page.goto(HOME_URL, { waitUntil: 'domcontentloaded', timeout: 30000 });
          } catch (e2) { await new Promise(r => setTimeout(r, 2000)); }
        }
      }
    }
    this._log('timed out waiting for manual login');
    return false;
  }

  async close() {
    try { if (this._loggedIn) await this._saveSession(); } catch {}
    try { await this.browser?.close(); } catch {}
    this.browser = this.context = this.page = null;
    this._loggedIn = false;
  }

  // ── Read: product list + current stock ───────────────────────────────────────

  // Fetch the full Roots product list with Guanyi's internal ids and current
  // on-hand. Issued as a cookie-auth POST from the logged-in page (same origin,
  // no token needed). Returns { rows:[{guanyiName, code, skuId, itemId,
  // itemSkuId, warehouseId, warehouseName, currentQty}], warehouseId }.
  async fetchListings() {
    if (!await this.ensureLoggedIn()) return null;
    let data;
    try {
      data = await this.page.evaluate(async (form) => {
        const body = new URLSearchParams(form).toString();
        const r = await fetch('/stock/message/stock_tenant/data/list', {
          method: 'POST',
          headers: { 'Content-Type': 'application/x-www-form-urlencoded; charset=UTF-8' },
          body, credentials: 'include',
        });
        let j = null; try { j = await r.json(); } catch (e) {}
        return { status: r.status, json: j };
      }, LIST_FORM);
    } catch (e) {
      // Drop the cached login latch. `_loggedIn` was only ever cleared by close(),
      // so a session that died server-side kept ensureLoggedIn() returning a stale
      // true and the page was never re-navigated — the daemon then failed every
      // cycle until a human intervened. Clearing it makes the next call re-probe,
      // which silently recovers whenever the cookie is in fact still good.
      this._loggedIn = false;
      this._log(`fetchListings error: ${String(e.message).slice(0, 100)}`);
      return null;
    }
    if (!data || data.status !== 200 || !data.json) {
      this._loggedIn = false;
      this._log(`fetchListings bad response: status=${data && data.status}`);
      return null;
    }
    const raw = data.json.rows || data.json.data || [];
    const rows = raw.map(r => {
      const name = r.itemName || r.itemSkuName || '';
      return {
        guanyiName:   name,
        code:         r.skuCode || r.code || r.itemBarcode || '',
        skuId:        r.skuId != null ? String(r.skuId) : '',
        itemId:       r.itemId != null ? String(r.itemId) : '',
        itemSkuId:    r.itemSkuId != null ? String(r.itemSkuId) : '',
        warehouseId:  r.warehouseId != null ? String(r.warehouseId) : '',
        warehouseName: r.warehouseName || '',
        // salableQty (可销) is what gzgrocery can sell — the number we mirror to.
        currentQty:   Math.round(Number(r.salableQty != null ? r.salableQty : r.qty) || 0),
        // 已停用 (deactivated) SKUs can't take a 库存调整单 — Guanyi rejects the
        // whole batch with 系统异常. Flag them so the daemon skips, never adjusts.
        disabled:     r.disable === true || r.skuDel === true || r.stopStatus === 1 || /已停用|已删除/.test(name),
      };
    }).filter(r => r.skuId);
    if (!this.warehouseId && rows.length && rows[0].warehouseId) this.warehouseId = rows[0].warehouseId;
    this._log(`fetched ${rows.length} Guanyi product(s)`);
    return { rows, warehouseId: this.warehouseId };
  }

  // ── Write: reconcile stock via 库存调整单 (Inventory Adjustment) ──────────────
  //
  // The sellable on-hand (正品库存 / salableQty) is moved ONLY by an APPROVED
  // 库存调整单, whose line `qty` is a SIGNED DELTA (+adds, −removes). The
  // 其他入库/出库单 only book 在途 (in-transit), so they are deliberately NOT used.
  // One adjustment document carries every product's delta; we pre-check, create,
  // then approve it. Each item: { skuId, itemId, itemSkuId, code, name,
  // currentQty, targetQty }. Returns items augmented with { ok, delta, skipped }.
  async applyDeltas(items) {
    // Not logged in / no warehouse yet = transient (session or first-read not
    // ready) — mark so the daemon retries instead of failing the rows terminally.
    if (!await this.ensureLoggedIn()) return items.map(it => ({ ...it, ok: false, transient: true }));
    if (!this.warehouseId) { await this.fetchListings(); }
    if (!this.warehouseId) { this._log('no warehouseId — cannot write'); return items.map(it => ({ ...it, ok: false, transient: true })); }

    const out = items.map(it => {
      const delta = Math.round(Number(it.targetQty) - Number(it.currentQty));
      return { ...it, delta, ok: false, skipped: delta === 0 };
    });
    const changed = out.filter(it => it.delta !== 0);
    if (!changed.length) return out; // already in sync — nothing to write

    // Fast path: push the whole batch as ONE adjustment document.
    const batch = await this._pushDocument(changed, { checkRetries: 3 });
    if (batch.ok) { for (const it of changed) it.ok = true; return out; }

    // Batch failed. checkStockAdjust validates the batch atomically, so a SINGLE
    // bad line (e.g. a product with leftover 在途/未审核 residue) makes Guanyi
    // reject the whole document with 系统异常 — stranding every innocent line.
    // Fall back to one document per line so the good lines still commit and only
    // the genuinely-bad line(s) stay flagged (and become identifiable).
    if (changed.length > 1) {
      this._log(`batch of ${changed.length} failed — isolating line-by-line`);
      const bad = [];
      for (const it of changed) {
        const r = await this._pushDocument([it], { checkRetries: 1 });
        it.ok = r.ok;
        it.transient = !r.ok;
        if (!r.ok) bad.push(`${it.name || it.skuId}(${it.delta > 0 ? '+' : ''}${it.delta})`);
        await this._humanPause(400, 900);
      }
      if (bad.length) this._log(`line-by-line: ${changed.length - bad.length} ok, ${bad.length} still failing → ${bad.slice(0, 10).join(', ')}${bad.length > 10 ? ' …' : ''}`);
    } else {
      // single-line batch already failed → transient, daemon retries later
      for (const it of changed) it.transient = true;
    }
    return out;
  }

  // Push ONE 库存调整单 for the given line items: pre-check (校验, retried — Guanyi
  // intermittently returns { code:'error', msg:'系统异常！' } for a valid
  // adjustment) → create → locate → approve (审核). Returns { ok, transient }.
  // Does not mutate items.
  async _pushDocument(lineItems, opts = {}) {
    const checkRetries = opts.checkRetries || 1;
    const payload = this._adjustPayload(lineItems.map(it => this._adjustLine(it)));
    const checkOk = (r) => r && /ok/i.test(String(r.code || r.msg || ''));

    let chk = null;
    for (let attempt = 1; attempt <= checkRetries; attempt++) {
      chk = await this._postJson('/stock/stock/stock_adjust_order_header/checkStockAdjust', payload);
      if (checkOk(chk)) break;
      if (checkRetries > 1) this._log(`checkStockAdjust attempt ${attempt}/${checkRetries} failed: ${JSON.stringify(chk).slice(0, 140)}`);
      if (attempt < checkRetries) await this._humanPause(1200, 2600);
    }
    if (!checkOk(chk)) return { ok: false, transient: true }; // Guanyi-side error — retry later

    const cr = await this._postJson('/stock/stock/stock_adjust_order_header/create', payload);
    if (!cr || String(cr.status) !== '200') { this._log(`adjust create failed: ${JSON.stringify(cr).slice(0, 180)}`); return { ok: false, transient: true }; }
    // create() carries no id → locate the just-saved (newest unapproved) doc for
    // our warehouse. The daemon writes serially, so the newest is ours.
    const headerId = await this._latestUnapprovedAdjustId();
    if (!headerId) { this._log('adjust saved but headerId not found to approve'); return { ok: false, transient: true }; }
    const approved = await this._approveAdjust(headerId);
    if (approved) this._log(`adjust ${headerId}: ${lineItems.length} line(s) [${lineItems.map(c => (c.delta > 0 ? '+' : '') + c.delta).join(',')}] approved=true`);
    return { ok: approved, transient: !approved };
  }

  // One 库存调整明细 line, signed delta in `qty`. Mirrors the captured create body.
  _adjustLine(it) {
    const cur = Math.round(Number(it.currentQty) || 0);
    return {
      stockQty: cur, skuId: String(it.skuId), itemSkuId: String(it.itemSkuId || ''), itemId: String(it.itemId || ''),
      itemCode: String(it.code || ''), itemSkuCode: String(it.code || ''),
      itemName: it.name || '', itemSimpleName: '', itemSkuName: it.name || '', itemCategoryName: null,
      pickableQty: cur, qty: Math.round(Number(it.delta)),
      stockQtyStatus: true, skuType: '0', pickQtyReject: 0, qtyReject: 0, note: '',
    };
  }

  _adjustPayload(lines) {
    return {
      currentFormId: 'no_repeat_sumit_stockAdjustAddOrUpdateSubmit',
      token: '', id: '', tenantId: '', version: '0',
      warehouseId: String(this.warehouseId),
      stockAdjustOrderDetailList: lines,
    };
  }

  // POST a JSON body from the logged-in page (cookie-auth). Returns parsed JSON
  // (or { _raw, _status } when the response isn't JSON), null on error.
  async _postJson(url, payload) {
    try {
      return await this.page.evaluate(async ({ url, payload }) => {
        const r = await fetch(url, { method: 'POST', headers: { 'Content-Type': 'application/json; charset=UTF-8' }, body: JSON.stringify(payload), credentials: 'include' });
        const t = await r.text(); let j = null; try { j = JSON.parse(t); } catch (e) { j = { _raw: t.slice(0, 200), _status: r.status }; }
        return j;
      }, { url, payload });
    } catch (e) { this._log(`_postJson ${url} error: ${String(e.message).slice(0, 100)}`); return null; }
  }

  // create() returns no id, so find the newest unapproved adjustment in our
  // warehouse (the one just saved — the daemon creates one at a time per store).
  async _latestUnapprovedAdjustId() {
    try {
      return await this.page.evaluate(async (wh) => {
        // Exact param shape the list grid uses (limit, dateType, approve, cancel).
        const body = new URLSearchParams({ page: '1', limit: '50', start: '0', dateType: '13', approve: 'false', cancel: 'false' }).toString();
        const r = await fetch('/stock/stock/stock_adjust_order_header/data/list', { method: 'POST', headers: { 'Content-Type': 'application/x-www-form-urlencoded; charset=UTF-8' }, body, credentials: 'include' });
        const t = await r.text(); let j = null; try { j = JSON.parse(t); } catch (e) { return null; }
        const rows = (j.rows || j.data || []).filter(x => String(x.warehouseId) === String(wh) && x.approve === false && !x.cancel);
        if (!rows.length) return null;
        rows.sort((a, b) => Number(b.createDate || 0) - Number(a.createDate || 0)); // newest first
        return String(rows[0].id);
      }, this.warehouseId);
    } catch (e) { this._log(`_latestUnapprovedAdjustId error: ${String(e.message).slice(0, 100)}`); return null; }
  }

  // Approve (审核) an adjustment so its delta commits to sellable stock. The UI
  // calls approveCheck (form ids=) then approve. approve needs a one-time
  // anti-resubmit token (no_repeat_sumit_stockAdjustApproveSubmit) which the
  // adjust LIST page embeds as a hidden input; its response is plain text
  // ("正在执行中" = queued/executing). Without that token approve returns
  // "调整单不存在".
  async _approveAdjust(headerId) {
    // Param shape confirmed from the page bundle: approve body =
    //   { purchaseId:<headerId>, currentFormId:"no_repeat_sumit_purchaseReturnApproveSubmit",
    //     no_repeat_sumit_purchaseReturnApproveSubmit:<token> }  (formData, text response)
    // The anti-resubmit token comes from the screen's page-init payload (n.result),
    // not a static hidden input; we pass it when available.
    const FORM_ID = 'no_repeat_sumit_purchaseReturnApproveSubmit';
    const tok = this._approveToken || '';
    try {
      // approveCheck first (form ids=), mirrors the UI.
      await this.page.evaluate(async ({ headerId }) => {
        await fetch('/stock/stock/stock_adjust_order_header/approveCheck', { method: 'POST', headers: { 'Content-Type': 'application/x-www-form-urlencoded; charset=UTF-8' }, body: 'ids=' + encodeURIComponent(headerId), credentials: 'include' });
      }, { headerId }).catch(() => {});
      const res = await this.page.evaluate(async ({ headerId, FORM_ID, tok }) => {
        const form = new URLSearchParams({ purchaseId: String(headerId), currentFormId: FORM_ID });
        if (tok) form.append(FORM_ID, tok);
        const r = await fetch('/stock/stock/stock_adjust_order_header/approve', { method: 'POST', headers: { 'Content-Type': 'application/x-www-form-urlencoded; charset=UTF-8' }, body: form.toString(), credentials: 'include' });
        return { status: r.status, text: (await r.text()).slice(0, 200) };
      }, { headerId, FORM_ID, tok });
      const ok = res && res.status === 200 && /正在执行|执行中|处理中|成功|success/i.test(res.text || '');
      if (!ok) this._log(`adjust approve rejected: status=${res && res.status} body=${res && res.text}`);
      return !!ok;
    } catch (e) { this._log(`_approveAdjust error: ${String(e.message).slice(0, 120)}`); return false; }
  }

  // ── Internals ────────────────────────────────────────────────────────────────

  async _saveSession() {
    if (!this.context) return;
    const state = await this.context.storageState();
    fs.writeFileSync(this.sessionFile, JSON.stringify(state));
  }

  _rand(min, max) { return Math.floor(min + Math.random() * (max - min + 1)); }
  async _humanPause(min = 600, max = 1600) { try { await this.page.waitForTimeout(this._rand(min, max)); } catch (e) {} }
  _log(msg) { console.log(`[guanyi:${this.storeCode}] ${msg}`); }
}

// ── Factory: one browser per store ───────────────────────────────────────────
const instances = {};
async function getBrowser(storeCode) {
  if (!instances[storeCode]) {
    const b = new GuanyiBrowser(storeCode);
    await b.init();
    instances[storeCode] = b;
  }
  return instances[storeCode];
}
async function closeAll() {
  for (const b of Object.values(instances)) await b.close();
  for (const k of Object.keys(instances)) delete instances[k];
}

module.exports = { GuanyiBrowser, getBrowser, closeAll, uuid };
