-- ===========================================================================
-- retail_order_counters — the order-number counter for PostgreSQL
-- Decisions §24, "ORDER NUMBERING IS A COUNTER ROW" (2026-08-11).
-- Piece 1 of two: schema and seeding. No application code depends on this yet.
-- ===========================================================================
--
-- WHY THIS FILE IS SEPARATE FROM THE SCHEMA RECORDS
--
-- It could not go in either of them, and that is worth stating rather than
-- leaving as a filing choice.
--
--   docs/tacet-postgres-schema-proposed.sql says, in its own header, "PROPOSAL
--   ONLY. Nothing here has been run" and "No new table, column, index or
--   constraint is invented." It is a 1:1 translation of the live SQLite schema.
--   This table exists in no SQLite database and never will. Putting it there
--   would make both of those sentences false.
--
--   docs/tacet-postgres-schema-as-built-2026-08-04.sql is a schema-only
--   pg_dump. Hand-editing a dump makes it a document that looks generated and
--   is not, and its date would then describe a state it no longer holds.
--
-- So this file is the DDL, and the as-built record is REGENERATED by a fresh
-- `pg_dump -s` once the table is created on the box. That is the mechanism that
-- already exists for keeping as-built honest; nothing else does.
--
-- NOTHING APPLIES THIS FILE AUTOMATICALLY. No script, hook or workflow reads
-- docs/*.sql — the only consumers are two diagnose scripts that PARSE the
-- as-built dump for column types. §24 records that the schema-change mechanism
-- is unresolved ("today schema changes happen via addColumn() calls in
-- database.js on restart, with no migrations folder and no down-migrations").
-- This is run by hand, once, against the `tacet` database.
--
--
-- WHY A COUNTER ROW AND NOT A SEQUENCE
--
-- Recorded in full in §24. In short: a row is covered by row-level security and
-- a sequence is not; a row survives the Orders stage by gaining a column, where
-- a sequence would have to be torn out and the mint function migrated on the
-- checkout a second time; and one global sequence would let any account read
-- platform-wide order volume off the gaps between its own numbers.
--
--
-- THE SHAPE, AND THE ONE THING IT IS FOR
--
--   series    the key. Not decoration — without it the table has no primary
--             key, and "there is exactly one row" would be an invariant
--             enforced by nothing. A second row in an unkeyed counter table is
--             a silent duplicate-order-number generator. 'TC' is the only row
--             this file creates.
--
--   last_no   the last number ISSUED, not the next one to issue. Chosen so the
--             seed value is the measured maximum with no arithmetic applied to
--             it — there is no +1 anywhere in the seeding path, so there is
--             nowhere for an off-by-one to hide. The mint reads the value it
--             has just written.
--
--   updated_at  a counter that silently stops moving is otherwise
--             undiagnosable. It costs nothing: the same row is already being
--             written by the same statement.
--
-- The format — the 'TC' prefix and the six-digit padding — deliberately stays
-- in the application, where it is today. Putting it in this table would create
-- a second source of truth for it. (When the prefix eventually has to become
-- per-account, because 'TC' is a constant inherited from the first business,
-- this table is its natural home and `series` is what makes that additive too.
-- That is a note, not a plan.)
--
--
-- HOW THIS BECOMES PER-ACCOUNT AT THE ORDERS STAGE
--
-- Stated honestly: the column add is additive, the key change is one constraint
-- swap on a table holding one row per account.
--
--   ALTER TABLE retail_order_counters ADD COLUMN account integer REFERENCES accounts (id);
--   UPDATE retail_order_counters SET account = (SELECT id FROM accounts /* by lookup */);
--   ALTER TABLE retail_order_counters ALTER COLUMN account SET NOT NULL;
--   ALTER TABLE retail_order_counters DROP CONSTRAINT retail_order_counters_pkey;
--   ALTER TABLE retail_order_counters ADD PRIMARY KEY (account, series);
--   ALTER TABLE retail_order_counters ENABLE ROW LEVEL SECURITY;
--   CREATE POLICY ... ;
--
-- and the application's WHERE gains a term. Note the backfill is written as a
-- LOOKUP, not as a literal id: §24 NO ACCOUNT IS SPECIAL-CASED, INCLUDING
-- ROOTS. No account number appears anywhere in this file, and none should
-- appear in that migration either.
--
-- ===========================================================================


-- ── 1. The table ───────────────────────────────────────────────────────────

CREATE TABLE retail_order_counters (
    series      text        NOT NULL,
    last_no     bigint      NOT NULL DEFAULT 0 CHECK (last_no >= 0),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT retail_order_counters_pkey PRIMARY KEY (series)
);

COMMENT ON TABLE retail_order_counters IS
  'Order-number counter. One row per number series (per account once the '
  'account column lands). Minted with UPDATE ... RETURNING; see decisions '
  'section 24, ORDER NUMBERING IS A COUNTER ROW.';

COMMENT ON COLUMN retail_order_counters.last_no IS
  'The last number ISSUED. The mint returns the value it writes; the seed is '
  'the measured maximum with no arithmetic applied.';


-- ── 2. The row ─────────────────────────────────────────────────────────────
--
-- Created at 0 by the DDL, deliberately, and raised by the seeding step below.
--
-- The row must exist before the application ever mints. If it does not, the
-- mint's UPDATE matches nothing, RETURNING yields no row, and the caller gets
-- an absent value where an order number should be — which is how a NULL or the
-- string "TCundefined" reaches a customer-facing column. With the row present
-- at 0, an unseeded counter fails instead on the UNIQUE constraint at
-- TC000001, loudly, on the first checkout. Both are failures; only one of them
-- is visible.

INSERT INTO retail_order_counters (series, last_no)
VALUES ('TC', 0)
ON CONFLICT (series) DO NOTHING;


-- ── 3. The seed — DELIBERATELY NOT EXECUTABLE FROM THIS FILE ───────────────
--
-- THIS FILE ENDS ABOVE. Applying it creates the table and the row at 0 and
-- does NOT seed. That is the point.
--
-- The first draft of this file ran the seed as its third statement, which
-- contradicted the rule written twenty lines further up in the same file:
-- SEEDING IS NOT A STEP OF THE SCHEMA BUILD. A file that states an ordering
-- rule and then violates it on apply is worse than one that never stated it,
-- because the rule reads as satisfied. Left as a comment so the statement is
-- readable next to the table it writes, and so nobody reconstructs it by hand.
--
-- THE SEEDING STEP IS scripts/postgres-full-copy/seed_order_counter.py.
-- It runs LAST, after the fresh copy AND after the delta pass, immediately
-- before traffic moves. It adds a receipt, two fatal preconditions, and a
-- non-zero exit when the counter is already ahead of the data — none of which
-- a bare UPDATE in a DDL file can give you.
--
-- What it runs, for reference only:
--
--   UPDATE retail_order_counters c
--      SET last_no = GREATEST(c.last_no, COALESCE((
--              SELECT MAX(substring(o.order_no from 3)::bigint)
--                FROM retail_orders o
--               WHERE o.order_no ~ '^TC[0-9]+$'
--          ), 0)),
--          updated_at = now()
--    WHERE c.series = 'TC';
--
-- The regex is load-bearing. `LIKE 'TC______'` is width-locked to exactly
-- eight characters and would silently exclude a 7-digit number, seeding BELOW
-- the true maximum — the precise failure the step exists to prevent. The cast
-- to bigint keeps the comparison numeric, so no text collation is involved.
-- GREATEST makes it idempotent and one-directional: a re-run can only raise
-- the counter, never lower it into numbers that already exist.


-- ── 4. What the application will run (PIECE 2 — NOT BUILT) ─────────────────
--
-- Recorded here so the mint and the seed are readable side by side; nothing
-- executes it yet. The design is in §24.
--
--   UPDATE retail_order_counters
--      SET last_no = last_no + 1, updated_at = now()
--    WHERE series = 'TC'
--   RETURNING last_no
--
-- One statement. Atomic. The row lock is held to commit, which serialises
-- checkouts exactly as BEGIN IMMEDIATE does today, and which stops serialising
-- across accounts the moment the account column lands.
--
-- THE PROBE LOOP MUST NOT SURVIVE ONTO THIS PATH. See §24.
