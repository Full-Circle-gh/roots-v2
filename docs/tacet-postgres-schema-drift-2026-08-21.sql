-- which is why `drift_guard.py` ships with this and refuses on any difference
-- rather than leaving the next one to be discovered the same way.
--
-- TYPES ARE CHOSEN FROM THE DATA, NOT FROM THE DECLARED SQLITE TYPE, following
-- the rules §24 already set:
--
--   * `ingredients.free_by_design` is INTEGER holding 0 on 604 rows and 1 on 3.
--     A flag, so `boolean` — §24 "Integer flags map to boolean".
--   * `ingredient_cost_skips.line_price` is REAL and one of its three values is
--     `4.55882`, five decimal places. It is a PER-UNIT price, so it takes
--     `numeric(14,6)` and NOT whole cents — cents would round it to 4.56 and
--     lose real precision, which is the exact defect §24 v3.0 reversed.
--   * `guessed_lat` / `guessed_lng` are coordinates, not money. `double
--     precision`, matching `retail_customer_addresses.lat`, `retail_stores.lat`
--     and `markets.lat`, all of which are already double precision.
--   * DATETIME columns take `timestamptz`; their values are naive text, which
--     §24 proved is UTC and which `gen.py` `q_ts` already handles.
--
-- GRANTS ARE DELIBERATELY ABSENT. `pg_default_acl` grants tacet_app
-- INSERT/SELECT/UPDATE/DELETE on any table and USAGE on any sequence created by
-- postgres in public. Verified against retail_order_counters, which was created
-- on 2026-08-11 by the same route with no GRANT in its own DDL and carries the
-- right privileges today. Confirm after applying rather than assuming.
--
-- Transactional. If any statement fails the whole thing rolls back.
