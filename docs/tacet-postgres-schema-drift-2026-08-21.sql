-- Records a purchase-order line whose cost could not be written to the
-- ingredient, so the Alerts page can say what went unpriced and why. Mirrors
-- the SQLite table exactly, including declaring a foreign key on ingredient_id
-- and NOT on po_id — the source declares only the one, and this file copies the
-- source's mind rather than improving on it.
CREATE TABLE ingredient_cost_skips (
    id            integer GENERATED BY DEFAULT AS IDENTITY,
    ingredient_id integer NOT NULL,
    po_id         integer,
    reason        text NOT NULL,
    line_unit     text,
    line_price    numeric(14,6),
    created_at    timestamptz DEFAULT now(),
    resolved_at   timestamptz,
    CONSTRAINT ingredient_cost_skips_pkey PRIMARY KEY (id),
    CONSTRAINT fk_ingredient_cost_skips_1 FOREIGN KEY (ingredient_id)
        REFERENCES ingredients(id)
);

COMMENT ON COLUMN ingredient_cost_skips.reason IS
    'One of a fixed set, stored raw so each can be counted on its own: '
    'no_pack_contents | unit_mismatch | unsupported_recipe_unit | no_pack_size | no_price.';
COMMENT ON COLUMN ingredient_cost_skips.resolved_at IS
    'Set when a later PO priced this item cleanly. The row stays as a record of '
    'what once went unpriced; only open rows (resolved_at IS NULL) alert.';

-- One row per subject that has switched push notifications off. Composite
-- primary key on (scope, subject_id), exactly as in SQLite — no identity column.
CREATE TABLE push_optouts (
    scope          text NOT NULL,
    subject_id     integer NOT NULL,
    linked_user_id integer,
    created_at     timestamptz DEFAULT now(),
    CONSTRAINT push_optouts_pkey PRIMARY KEY (scope, subject_id)
);

COMMENT ON COLUMN push_optouts.scope IS 'user | operator';
COMMENT ON COLUMN push_optouts.linked_user_id IS 'operator scope only';

